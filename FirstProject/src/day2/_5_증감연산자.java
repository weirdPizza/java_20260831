package day2;

public class _5_증감연산자 {

	public static void main(String[] args) {
		int num1 = 10;
		num1++; // 1씩 증가
		num1++; 
		num1++;
		System.out.println(num1); // 13
	
		num1--; // 1씩 감소
		num1--;
		System.out.println(num1); // 11
		
		++num1; // 1씩 증가
		++num1;
		System.out.println(num1); // 13
	}

}
